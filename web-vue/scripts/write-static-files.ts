import {
  PROTECTED_ROUTE_PREFIXES,
  PROTECTED_SPA_SHELL_ASSET_PATH,
  PUBLIC_SSG_ROUTES
} from "@hvbc/contracts/routes";
import { BROWSER_SECURITY_HEADERS, STRICT_TRANSPORT_SECURITY } from "@hvbc/contracts/security-headers";
import { IMMUTABLE_ASSETS_CACHE_CONTROL, IMMUTABLE_ASSETS_PREFIX } from "@hvbc/contracts/static-assets";

import { appOrigin } from "./app-origin";

const outputDirectory = "../dist/web-vue";
const origin = appOrigin("../wrangler.jsonc");

function headerRule(path: string, headers: Record<string, string>): string {
  return [path, ...Object.entries(headers).map(([name, value]) => `  ${name}: ${value}`)].join("\n");
}

const headers = [
  "# Generated by web-vue/scripts/write-static-files.ts from @hvbc/contracts/security-headers.",
  headerRule("/*", { ...BROWSER_SECURITY_HEADERS, "Strict-Transport-Security": STRICT_TRANSPORT_SECURITY }),
  headerRule(`${IMMUTABLE_ASSETS_PREFIX}*`, { "Cache-Control": IMMUTABLE_ASSETS_CACHE_CONTROL })
].join("\n\n");

const robots = [
  "User-agent: *",
  ...[...PROTECTED_ROUTE_PREFIXES, PROTECTED_SPA_SHELL_ASSET_PATH].map((path) => `Disallow: ${path}`),
  "",
  `Sitemap: ${origin}/sitemap.xml`
].join("\n");

const sitemap = [
  '<?xml version="1.0" encoding="UTF-8"?>',
  '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
  ...PUBLIC_SSG_ROUTES.map((route) => `  <url><loc>${origin}${route}</loc></url>`),
  "</urlset>"
].join("\n");

await Promise.all([
  // Outside the asset directory, so Cloudflare never publishes it; the Bun server
  // reads it to refuse a production start with a different APP_ORIGIN.
  Bun.write(`${outputDirectory}/../build-info.json`, `${JSON.stringify({ appOrigin: origin })}\n`),
  Bun.write(`${outputDirectory}/_headers`, `${headers}\n`),
  Bun.write(`${outputDirectory}/robots.txt`, `${robots}\n`),
  Bun.write(`${outputDirectory}/sitemap.xml`, `${sitemap}\n`)
]);
